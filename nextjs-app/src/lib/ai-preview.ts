/**
 * プレビューの語彙（ADR-0006）。
 *
 * WHY 画面から切り離すか: ここにあるのは**結果を見て聞き返しかどうかを決める**規則で
 * ある。契約にフラグを足さずに画面が判断すると決めた（#65）ので、判断はコードのどこかに
 * 置かれる。JSX の中に置くと、AI が一部しか埋めなかった応答を実際に作らない限り
 * 確かめられない。
 *
 * 3タブが同じ形の一覧を出すのは、プレビューの中身が「何が埋まって何が埋まらなかったか」
 * に尽きるため。フォームの状態モデルはタブごとに分けたまま（#23）で、共有するのは
 * この**結果の見せ方**だけに留める。
 */

/**
 * プレビューに並ぶ1行（設計書 3.6.1節）。
 *
 * 3タブで行の意味が違う。交通ICは欄（「出発日: 2026-10-15」）、候補日程は作られた
 * 候補日程そのもの（「10月15日(火) 14:00–15:00」）、参加可否は候補日程への判定
 * （「10月15日(火) 14:00–15:00: 現地で出席」）である。
 */
export type PreviewItem = {
  /** React の key。欄名や候補日程の識別子など、一覧の中で一意なもの。 */
  key: string;
  /** 行の見出し。欄名、または候補日程の表示名。 */
  label: string;
  /**
   * 抽出・判定できた値。
   *
   * - 文字列 — 埋まった
   * - `null` — **埋まらなかった**（行は残す。何が足りないかを聞き返しに使う）
   * - 省略 — 値の欄を持たない行（候補日程のように、見出しそのものが結果のもの）
   *
   * `null` と省略を分けるのは、どちらも「値が無い」なのに意味が逆だから。候補日程は
   * 値が無いまま埋まっている。混ぜると、生成に成功した候補日程がそのまま聞き返しの
   * 対象になる。
   */
  value?: string | null;
  /**
   * 反映しても**この行は変わらない**。手で入れた値を守るため（#38）。
   *
   * WHY 埋まった行と分けるか: AI は読み取れているので `value` は出せるが、押しても
   * フォームには入らない。緑のチェックで並べると、プレビューが「押したら入るもの」を
   * 偽って見せることになり、ADR-0006 が閉じたかった経路（見ていないものが入る／
   * 見たものが入らない）が裏返しで開く。事後の `ApplyReport` では代われない —
   * あれは押した後の話で、押すかどうかの判断には間に合わない。
   */
  preserved?: boolean;
  /**
   * この行が空でも**聞き返しに数えない**（#168）。
   *
   * WHY 要るか: 聞き返しの分母は「この呼び出しが担う仕事」であって、タブの全欄では
   * ない。交通ICがフォーム主導になり（ADR-0017）、追加指示を空にしてフォームだけで
   * 生成できるようになると、借りる日・返す日時・利用目的は**言及が無いので読み取れ
   * ないのが正しい**。分母に入れたままだと、経路と運賃がきちんと返った成功の回が
   * 毎回黄の聞き返しとして出て、職員は何を足せばよいのか分からないまま書き直しを
   * 促される。**行そのものは残す** — 何が埋まらなかったかは見えている必要がある。
   */
  optional?: boolean;
  /**
   * 錠の行に添える理由。既定は「手入力のため変更しません」。
   *
   * WHY 差し替えられるようにするか: 反映が加算になったタブ（候補日程）では、入らない
   * 理由が手入力の保護ではない — 既に選んだ候補日程と重なるか、件数が入力契約の上限を
   * 超えるかである。既定の文言のままだと、職員は自分がどこで手入力したのかを探す。
   */
  preservedReason?: string;
};

/**
 * AI提案の内訳のひと区画（#172。設計書 3.6.3節）。
 *
 * WHY 抽出項目の一覧（`PreviewItem`）と分けるか: **内訳の行は欄に対応しない。**
 * プレビューには2つの役割があり、一覧は「押す前に何が入るか」を、内訳は「AI が何を
 * 調べてなぜそれを選んだか」を見せる。混ぜると聞き返しの判定（`previewTone`）の
 * 分母に欄でない行が入り、埋まった欄の数と関係のないところで黄に倒れる。
 *
 * **中身を渡すのは交通ICだけ。** 会議3タブは調べものをしないので内訳が無く、
 * 渡さなければ領域ごと出ない。
 */
export type BreakdownSection = {
  /** React の key。区画の識別子。 */
  key: string;
  /** 区画の見出し（「検索条件」など）。 */
  label: string;
  /** 区画に並ぶ行。「出発地：虎ノ門ヒルズ（最寄：虎ノ門駅）」のような1行の文字列。 */
  lines: readonly string[];
};

/**
 * プレビューのメッセージの見た目（#65）。
 *
 * 赤（`AiErrorCode`）はここに無い。あれは結果が返らなかったときなので、
 * プレビュー自体が出ない。
 */
export type PreviewTone =
  /** 通常のAI生成メッセージ。青。 */
  | "filled"
  /** 聞き返し。黄。結果が空、または一部しか埋まらなかったとき。 */
  | "incomplete";

/**
 * 一覧を見て聞き返しかどうかを決める（#65）。
 *
 * WHY 契約のフラグではなく画面の判断か: 「一部しか埋まらなかった」の分母がタブごとに
 * 違う（交通ICは移動経路と1人あたり運賃の2欄、参加可否は渡した候補日程の件数、候補日程は分母が無く
 * 0件かどうかだけ）。契約に「聞き返しである」を載せるとモデルがそれを申告することに
 * なり、**埋まっていないのに埋まったと申告された応答**を画面が信じてしまう。
 * 一覧はモデルの申告ではなく画面が結果から組んだものなので、こちらを見るほうが確か。
 *
 * 空（1行も無い）を聞き返しに含めるのは、候補日程タブが0件の応答をそう表すため。
 *
 * 分母から外れる行は `optional` が持つ（#168）。分母をタブごとの関数に持たせないのは、
 * どの行を数えるかは**行を組んだ側**にしか分からないため。
 */
export function previewTone(items: readonly PreviewItem[]): PreviewTone {
  if (items.length === 0) return "incomplete";
  return items.some((item) => item.value === null && item.optional !== true)
    ? "incomplete"
    : "filled";
}

/**
 * 押したらフォームが変わるか（ADR-0006）。
 *
 * WHY 要るか: 変わらないのに反映を押させると、`ApplyReport` が「フォームは変わって
 * いません」と言い、アシスタントはそれでも縮む。**押す意味の無い操作**を出さない。
 * 起きるのは、読み取れた行が1つも無いとき（候補日程の0件応答）と、読み取れた行が
 * すべて手入力で守られているときである。
 */
export function hasApplicableItems(items: readonly PreviewItem[]): boolean {
  return items.some((item) => item.value !== null && item.preserved !== true);
}

/**
 * アシスタントを縮めて非AI経路へ移すまでの連続失敗回数（設計書 3.7節）。
 *
 * WHY 回数で切るか: 同じ失敗が続いているとき、職員に残っている手は書き直しではなく
 * 手入力である。エラーの種別だけで決められないのは、TIMEOUT のように**1回目は再送を
 * 勧めるのが正しい**種別があるため（`error-guidance.ts`）。3回目でその勧めを撤回する。
 */
export const MAX_CONSECUTIVE_FAILURES = 3;
